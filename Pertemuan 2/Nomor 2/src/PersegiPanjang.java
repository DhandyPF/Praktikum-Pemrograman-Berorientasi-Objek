class PersegiPanjang {
    // Hitung Luas
    int hitungLuas(int panjang, int lebar){
        int luas = panjang * lebar;
        return (luas);
    }

    // Hitung Keliling
    int hitungKeliling(int panjang, int lebar){
        int keliling = 2 * (panjang + lebar);
        return (keliling);
    }
}